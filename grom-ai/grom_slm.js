function normalizeWord(w) {
    if (SYNONYMS[w]) return SYNONYMS[w];
    let wClean = w;
    if (wClean.length >= 6) {
        for (const suf of SUFFIXES) {
            if (wClean.endsWith(suf) && wClean.length - suf.length >= 4) {
                wClean = wClean.slice(0, -suf.length);
                break;
            }
        }
    }
    return SYNONYMS[wClean] || wClean;
}

function normalize(q) {
    q = String(q).toLowerCase().trim().replace(/ё/g, 'е');
    q = q.replace(/[^a-zа-я0-9\s.\-]/g, ' ').replace(/\s+/g, ' ').trim();
    const out = [];
    for (const w of q.split(' ')) {
        if (!w) continue;
        out.push(normalizeWord(w));
    }
    return out.join(' ');
}

function tokensOf(q) {
    const words = normalize(q).match(/[a-zа-я0-9]+/g) || [];
    return words.filter(w => !STOP_WORDS.has(w) && w.length >= 3);
}

class SearchIndex {
    constructor(data) {
        this.data = data;
        this.docs = data.map(pair => {
            const qTokens = tokensOf(pair.question);
            const keyTokens = [];
            for (const k of pair.keys || []) keyTokens.push(...tokensOf(k));
            return { pair, qTokens, keyTokens, allTokens: [...qTokens, ...keyTokens] };
        });
        this.df = new Map();
        for (const doc of this.docs) {
            const seen = new Set(doc.allTokens);
            for (const t of seen) this.df.set(t, (this.df.get(t) || 0) + 1);
        }
        this.N = this.docs.length;
    }

    idf(token) {
        const df = this.df.get(token) || 0;
        if (df === 0) return 0;
        return Math.log((this.N + 1) / (df + 0.5)) + 1;
    }

    scorePair(queryTokens, doc) {
        if (!queryTokens.length) return 0;
        const qTF = new Map();
        for (const t of queryTokens) qTF.set(t, (qTF.get(t) || 0) + 1);
        const dTF = new Map();
        for (const t of doc.allTokens) dTF.set(t, (dTF.get(t) || 0) + 1);

        let dot = 0, qNorm = 0, dNorm = 0, matched = 0;
        for (const [t, qCount] of qTF) {
            const w = this.idf(t);
            qNorm += Math.pow(qCount * w, 2);
            if (dTF.has(t)) {
                dot += (qCount * w) * (dTF.get(t) * w);
                matched++;
            }
        }
        for (const [t, dCount] of dTF) {
            const w = this.idf(t);
            dNorm += Math.pow(dCount * w, 2);
        }
        if (qNorm === 0 || dNorm === 0) return 0;
        const cosine = dot / (Math.sqrt(qNorm) * Math.sqrt(dNorm));

        const coverage = matched / qTF.size;
        if (coverage < 0.5) return cosine * coverage * 0.5;
        return cosine;
    }

    search(userQ) {
        const qTokens = tokensOf(userQ);
        if (qTokens.length === 0) return { answer: null, score: 0, matched: null };

        if (qTokens.length === 1) {
            const df = this.df.get(qTokens[0]) || 0;
            if (df / this.N > 0.08) {
                return { answer: null, score: 0, matched: null, reason: 'too_common_token' };
            }
        }

        let best = null, bestScore = 0;
        for (const doc of this.docs) {
            const s = this.scorePair(qTokens, doc);
            if (s > bestScore) { bestScore = s; best = doc.pair; }
        }
        return {
            answer: best ? best.answer : null,
            score: bestScore,
            matched: best ? best.question : null,
        };
    }
}

let SEARCH_INDEX = null;
function getIndex(data) {
    if (!SEARCH_INDEX) SEARCH_INDEX = new SearchIndex(data);
    return SEARCH_INDEX;
}

function similaritySearch(userQ, data, threshold) {
    threshold = threshold === undefined ? 0.45 : threshold;
    const idx = getIndex(data);
    const r = idx.search(userQ);
    if (r.answer && r.score >= threshold) return r;
    return { answer: null, score: r.score, matched: null };
}

function keywordSearch(userQ, data, minHits) {
    minHits = minHits === undefined ? 2 : minHits;
    const qTokens = new Set(tokensOf(userQ));
    const normUser = normalize(userQ);

    let best = null, bestScore = 0;
    for (const pair of data) {
        const keys = pair.keys || [];
        if (!keys.length) continue;
        let hits = 0;

        for (const key of keys) {
            const kNorm = normalize(key);
            if (!kNorm) continue;

            const paddedUser = ` ${normUser} `;
            const paddedKey = ` ${kNorm} `;
            if (kNorm.length >= 3 && paddedUser.includes(paddedKey)) {
                const wordsInKey = kNorm.split(' ').length;
                if (wordsInKey <= 2 && kNorm.length <= 15) {
                    hits += 20;
                } else {
                    hits += 8;
                }
                continue;
            }

            if (qTokens.size === 0) continue;
            const kTok = tokensOf(key);
            let tokenHits = 0;
            for (const t of kTok) if (qTokens.has(t)) tokenHits++;
            if (tokenHits > 0 && tokenHits === kTok.length && kTok.length >= 2) {
                hits += tokenHits * 2;
            } else if (tokenHits >= 1 && kTok.length === 1) {
                hits += 2;
            }
        }
        if (hits > bestScore) { bestScore = hits; best = pair; }
    }
    if (best && bestScore >= minHits) {
        return { answer: best.answer, hits: bestScore, matched: best.question };
    }
    return { answer: null, hits: bestScore, matched: null };
}

function sequenceMatcherRatio(a, b) {
    if (a === b) return 1;
    if (!a || !b || a.length < 2 || b.length < 2) return 0;
    const bigrams = (s) => {
        const m = new Map();
        for (let i = 0; i < s.length - 1; i++) {
            const bi = s.substr(i, 2);
            m.set(bi, (m.get(bi) || 0) + 1);
        }
        return m;
    };
    const A = bigrams(a), B = bigrams(b);
    let matches = 0;
    for (const [bi, c] of A) if (B.has(bi)) matches += Math.min(c, B.get(bi));
    const denom = (a.length - 1) + (b.length - 1);
    if (denom <= 0) return 0;
    const r = (2 * matches) / denom;
    return isFinite(r) ? Math.min(r, 1) : 0;
}

function jaccardSet(a, b) {
    if (!a.size || !b.size) return 0;
    let inter = 0;
    for (const x of a) if (b.has(x)) inter++;
    return inter / (a.size + b.size - inter);
}

