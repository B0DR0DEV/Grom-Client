function fmtTime(seconds) {
    seconds = Math.max(0, Math.floor(seconds));
    if (seconds < 60) return `${seconds}с`;
    let m = Math.floor(seconds / 60), s = seconds % 60;
    if (m < 60) return `${m}м ${s}с`;
    let h = Math.floor(m / 60); m = m % 60;
    return `${h}ч ${m}м ${s}с`;
}

function drawProgressBar(current, total, width, prefix, suffix, barColor) {
    width = width || 30;
    prefix = prefix || '';
    suffix = suffix || '';
    barColor = barColor || C.BRIGHT_GREEN;
    total = Math.max(total, 1);
    const ratio = Math.min(Math.max(current / total, 0), 1);
    const filled = Math.round(width * ratio);
    const empty = width - filled;
    const bar = `${barColor}${'█'.repeat(filled)}${C.DIM}${'░'.repeat(empty)}${C.RESET}`;
    const percent = ` ${(ratio * 100).toFixed(1).padStart(5)}%`;
    let line = `${prefix}${bar}${percent}`;
    if (suffix) line += `  ${C.DIM}${suffix}${C.RESET}`;
    return line;
}

