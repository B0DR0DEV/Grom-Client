                const prefix = `  ${C.BRIGHT_CYAN}ep ${String(epoch).padStart(3)}/${epochs}${C.RESET} `;
                const suffix = `loss=${C.BRIGHT_YELLOW}${curLoss.toFixed(4)}${C.RESET}  ` +
                    `ETA ${C.BRIGHT_GREEN}${fmtTime(eta)}${C.RESET}`;
