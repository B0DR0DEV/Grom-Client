function extractVersion(text) {
    const m = String(text).match(/\b(1\.\d{1,2}(?:\.\d{1,2})?)\b/);
    if (!m) return null;
    return m[1];
}

function javaForVersion(mcVersion) {
    if (!mcVersion) return null;
    const parts = mcVersion.split('.').map(n => parseInt(n, 10));
    const minor = parts[1] || 0;
    if (minor <= 16) return "Java 8";
    if (minor === 17) return "Java 16";
    if (minor === 18 || minor === 19 || minor === 20) return "Java 17";
    if (minor >= 21) return "Java 21";
    return null;
}

function detectTheme(text) {
    const norm = normalize(text);
    const matches = [];
    for (const theme of THEME_PRIORITY) {
        const cat = MODPACK_CATALOG[theme];
        for (const kw of cat.keywords) {
            const kwNorm = normalize(kw);
            if (norm.includes(kwNorm)) {
                matches.push({ theme, kwLen: kwNorm.length });
                break;
            }
        }
    }
    if (!matches.length) return null;
    matches.sort((a, b) => b.kwLen - a.kwLen);
    return matches[0].theme;
}

function isModpackRequest(text) {
    const norm = normalize(text);
    const triggers = [
        "собери сборк", "собрать сборк", "сделай сборк", "составь сборк",
        "сборка для", "сборку для", "сборка на", "сборку на",
        "сборка модов", "сборку модов",
        "собери мод", "собрать мод", "подбери мод", "подбор мод",
        "посоветуй мод", "порекомендуй мод",
        "моды для", "модов для",
    ];
    return triggers.some(t => norm.includes(normalize(t)));
}

function buildModpackResponse(theme, mcVersion) {
    const cat = MODPACK_CATALOG[theme];
    if (!cat) return null;

    const lines = [];

    // ─── Заголовок ───
    lines.push('');
    lines.push(`${C.BRIGHT_MAGENTA}${C.BOLD}╔${'═'.repeat(58)}╗${C.RESET}`);
    const title = `${cat.emoji}  ${cat.name.toUpperCase()}${mcVersion ? ` · Minecraft ${mcVersion}` : ''}`;
    const padTitle = Math.max(0, 58 - stripAnsi(title).length);
    lines.push(`${C.BRIGHT_MAGENTA}${C.BOLD}║${C.RESET}  ${C.BOLD}${C.BRIGHT_WHITE}${title}${C.RESET}${' '.repeat(padTitle)}${C.BRIGHT_MAGENTA}${C.BOLD}║${C.RESET}`);
    lines.push(`${C.BRIGHT_MAGENTA}${C.BOLD}╚${'═'.repeat(58)}╝${C.RESET}`);
    lines.push(`${C.ITALIC}${C.DIM}${cat.description}${C.RESET}`);

    // ─── Группы ───
    for (const group of cat.groups) {
        lines.push('');
        lines.push(`${C.BRIGHT_CYAN}${C.BOLD}${group.title}${C.RESET}`);
        if (group.hint) {
            lines.push(`${C.DIM}${group.hint}${C.RESET}`);
        }
        for (const m of group.mods) {
            if (m.note) {
                lines.push(`  ${C.BRIGHT_GREEN}•${C.RESET} ${C.BOLD}${m.name}${C.RESET} ${C.DIM}— ${m.note}${C.RESET}`);
            } else {
                lines.push(`  ${C.BRIGHT_GREEN}•${C.RESET} ${C.BOLD}${m.name}${C.RESET}`);
            }
        }
    }

    // ─── Подсказка по версии и Java ───
    lines.push('');
    lines.push(`${C.BRIGHT_BLUE}${C.BOLD}💡 Подсказка:${C.RESET}`);
    if (mcVersion) {
        const jv = javaForVersion(mcVersion);
        lines.push(`  • Все моды ставь под версию ${C.BOLD}${mcVersion}${C.RESET} в Modrinth (фильтр по версии).`);
        if (jv) lines.push(`  • Для MC ${C.BOLD}${mcVersion}${C.RESET} нужна ${C.BOLD}${jv}${C.RESET} — Grom Client скачает её сам.`);
    } else {
        lines.push(`  • Уточни версию, например: ${C.ITALIC}«собери PvP сборку на 1.20.1»${C.RESET} — подскажу Java.`);
    }
    lines.push(`  • Если поставить моды на Vanilla — лаунчер сам предложит переключить сборку на Fabric.`);

    // ─── Предупреждение (для PvP) ───
    if (cat.warning) {
        lines.push('');
        lines.push(`${C.BRIGHT_YELLOW}${C.BOLD}⚠️  Важно:${C.RESET} ${C.DIM}${cat.warning}${C.RESET}`);
    }

    // ─── Как установить ───
    lines.push('');
    lines.push(`${C.DIM}Как установить: открой сборку в Grom Client → вкладка «Моды» → введи название → «Установить».${C.RESET}`);

    return lines.join('\n');
}

// Утилита: длина строки без ANSI-кодов (для выравнивания рамки)
function stripAnsi(s) {
    return String(s).replace(/\x1b\[[0-9;]*m/g, '');
}

function tryBuildModpack(userQ) {
    if (!isModpackRequest(userQ)) return null;

    const theme = detectTheme(userQ);
    const version = extractVersion(userQ);

    if (!theme) {
        const themesList = THEME_PRIORITY.map(t => `${MODPACK_CATALOG[t].emoji} ${MODPACK_CATALOG[t].name}`).join(', ');
        return {
            text: `Понял, что хочешь сборку${version ? ` на ${version}` : ''}, но не понял тему. ` +
                  `Уточни, например: «собери PvP сборку на 1.20.1».\n\n${C.DIM}Доступные темы:${C.RESET}\n  ${themesList}`,
            source: 'modpack-clarify'
        };
    }

    const text = buildModpackResponse(theme, version);
    return { text, source: 'modpack' };
}

