function smartAnswer(userQ, data, model, verbose) {
    verbose = verbose !== false;
    const cleaned = String(userQ || '').trim();

    if (cleaned.length < 2) {
        return { text: 'Задай вопрос подлиннее, пожалуйста.', source: 'reject' };
    }

    // 0) Сборка сборок — самый приоритетный режим
    const modpack = tryBuildModpack(cleaned);
    if (modpack) {
        if (verbose) console.log(`   ${C.DIM}[modpack] собран список модов по категориям${C.RESET}`);
        return modpack;
    }

    // 1) Keyword
    const kw = keywordSearch(cleaned, data, 2);
    if (kw.answer) {
        if (verbose) console.log(`   ${C.DIM}[keywords ${C.BRIGHT_YELLOW}hits=${kw.hits}${C.DIM}] ← "${kw.matched}"${C.RESET}`);
        return { text: kw.answer, source: 'keywords' };
    }

    // 2) TF-IDF
    const sim = similaritySearch(cleaned, data, 0.45);
    if (sim.answer) {
        if (verbose) console.log(`   ${C.DIM}[similarity ${C.BRIGHT_GREEN}${sim.score.toFixed(2)}${C.DIM}] ← "${sim.matched}"${C.RESET}`);
        return { text: sim.answer, source: 'similarity' };
    }

    // 3) Fallback
    if (model) {
        if (verbose) console.log(`   ${C.DIM}[generation] пробую генерацию...${C.RESET}`);
        const gen = model.generate(cleaned, 0.7, 5);
        if (gen) {
            if (verbose) console.log(`   ${C.DIM}[generation ✓]${C.RESET}`);
            return { text: gen, source: 'generation' };
        }
    }

    if (verbose) console.log(`   ${C.DIM}[no match]${C.RESET}`);
    return {
        text: 'Не знаю такого. Спроси что-нибудь про Grom Client, моды, сборки или Minecraft. ' +
              'Могу собрать сборку — напиши, например, «собери PvP сборку на 1.20.1».',
        source: 'unknown'
    };
}

