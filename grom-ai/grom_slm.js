const PAD_TOKEN = '<pad>';
const BOS_TOKEN = '<bos>';
const EOS_TOKEN = '<eos>';
const UNK_TOKEN = '<unk>';

class BPETokenizer {
    constructor() {
        this.tokenToId = new Map();
        this.idToToken = new Map();
        this.merges = new Map();
    }
    _addToken(t) {
        if (!this.tokenToId.has(t)) {
            const id = this.tokenToId.size;
            this.tokenToId.set(t, id);
            this.idToToken.set(id, t);
        }
    }
    tokenToIdGet(t) { return this.tokenToId.get(t); }
    get vocabSize() { return this.tokenToId.size; }

    train(corpus, vocabSize) {
        vocabSize = vocabSize || 2000;
        [PAD_TOKEN, BOS_TOKEN, EOS_TOKEN, UNK_TOKEN].forEach(t => this._addToken(t));

        const wordFreq = new Map();
        for (const text of corpus) {
            for (const w of text.split(/\s+/)) {
                if (w) wordFreq.set(w, (wordFreq.get(w) || 0) + 1);
            }
        }
        for (const w of wordFreq.keys()) {
            for (const c of w) this._addToken(c);
        }
        const wordSplits = new Map();
        for (const w of wordFreq.keys()) wordSplits.set(w, ['▁', ...[...w]]);

        const MAX_MERGES = Math.max(0, vocabSize - this.tokenToId.size);
        for (let step = 0; step < MAX_MERGES; step++) {
            const pairCounts = new Map();
            for (const [w, freq] of wordFreq) {
                const chars = wordSplits.get(w);
                for (let i = 0; i < chars.length - 1; i++) {
                    const pair = chars[i] + '\u0001' + chars[i + 1];
                    pairCounts.set(pair, (pairCounts.get(pair) || 0) + freq);
                }
            }
            if (pairCounts.size === 0) break;
            let bestPair = null, bestCount = 0;
            for (const [pair, count] of pairCounts) {
                if (count > bestCount) { bestCount = count; bestPair = pair; }
            }
            if (bestCount < 2) break;
            const [a, b] = bestPair.split('\u0001');
            const newToken = a + b;
            if (this.tokenToId.has(newToken)) continue;
            this._addToken(newToken);
            this.merges.set(a + '\u0001' + b, newToken);
            for (const w of wordFreq.keys()) {
                const chars = wordSplits.get(w);
                const merged = [];
                let i = 0;
                while (i < chars.length) {
                    if (i < chars.length - 1 && chars[i] === a && chars[i + 1] === b) {
                        merged.push(newToken); i += 2;
                    } else { merged.push(chars[i]); i += 1; }
                }
                wordSplits.set(w, merged);
            }
        }
    }
    _encodeWord(word) {
        let chars = ['▁', ...[...word]];
        let changed = true;
        while (changed) {
            changed = false;
            const merged = [];
            let i = 0;
            while (i < chars.length) {
                if (i < chars.length - 1) {
                    const pair = chars[i] + '\u0001' + chars[i + 1];
                    if (this.merges.has(pair)) {
                        merged.push(this.merges.get(pair));
                        i += 2; changed = true; continue;
                    }
                }
                merged.push(chars[i]); i += 1;
            }
            chars = merged;
        }
        return chars.map(c => this.tokenToId.has(c) ? this.tokenToId.get(c) : this.tokenToId.get(UNK_TOKEN));
    }
    encode(text) {
        const ids = [];
        for (const w of String(text).split(/\s+/)) {
            if (!w) continue;
            ids.push(...this._encodeWord(w));
        }
        return ids;
    }
    decode(ids) {
        const parts = [];
        for (const id of ids) {
            const t = this.idToToken.get(id);
            if (t === undefined) continue;
            if (t === PAD_TOKEN || t === BOS_TOKEN || t === EOS_TOKEN) continue;
            parts.push(t);
        }
        return parts.join('').replace(/▁/g, ' ').trim();
    }
    save(filepath) {
        fs.writeFileSync(filepath, JSON.stringify({
            tokenToId: [...this.tokenToId.entries()],
            merges: [...this.merges.entries()],
        }), 'utf-8');
    }
    static load(filepath) {
        const data = JSON.parse(fs.readFileSync(filepath, 'utf-8'));
        const tok = new BPETokenizer();
        tok.tokenToId = new Map(data.tokenToId);
        for (const [k, v] of tok.tokenToId) tok.idToToken.set(v, k);
        tok.merges = new Map(data.merges);
        return tok;
    }
}

