// 6. FALLBACK-МОДЕЛЬ
// ══════════════════════════════════════════════════════════════════════════

class FallbackLM {
    constructor(data, tokenizer, cfg) {
        this.data = data;
        this.tokenizer = tokenizer;
        this.cfg = cfg;
    }
    generate(question, temperature, topK) {
        temperature = temperature === undefined ? 0.7 : temperature;
        topK = topK === undefined ? 5 : topK;
        const norm = normalize(question);
        const userTokens = new Set(tokensOf(question));
        if (!norm || norm.length < 3) return null;
        if (userTokens.size === 0) return null;

        const scored = [];
        for (const pair of this.data) {
            const seq = sequenceMatcherRatio(norm, normalize(pair.question));
            const jac = jaccardSet(userTokens, new Set(tokensOf(pair.question)));
            const score = 0.5 * seq + 0.5 * jac;
            scored.push({ pair, score });
        }
        scored.sort((a, b) => b.score - a.score);
        const top = scored.slice(0, topK).filter(s => s.score > 0.4);
        if (!top.length) return null;

        const weights = top.map(s => Math.exp(s.score / temperature));
        const totalW = weights.reduce((a, b) => a + b, 0);
        let r = Math.random() * totalW;
        for (let i = 0; i < top.length; i++) {
            r -= weights[i];
            if (r <= 0) return top[i].pair.answer;
        }
        return top[0].pair.answer;
    }
    save(filepath) {
        fs.writeFileSync(filepath, JSON.stringify({
            cfg: this.cfg,
            vocabSize: this.tokenizer.vocabSize,
            datasetSize: this.data.length,
            timestamp: new Date().toISOString(),
        }, null, 2), 'utf-8');
    }
    static load(filepath, data, tokenizer) {
        const obj = JSON.parse(fs.readFileSync(filepath, 'utf-8'));
        return new FallbackLM(data, tokenizer, obj.cfg);
    }
}

